/**
 * Everything a certificate template needs, already resolved: no database, no
 * storage, no Node APIs. The same object renders the admin preview (browser),
 * the PDF and the PNG (Playwright), so all three are identical.
 */
export type CertificateDocument = {
  /** null while the certificate is a draft (the number is assigned on issue). */
  certificateNumber: string | null;
  revision: number;
  isDraft: boolean;
  /** Diagonal mark on every page: drafts and template samples can never pass as real certificates. */
  watermark: "draft" | "sample" | null;
  company: {
    name: string;
    legalForm: string | null;
    address: string;
    postalCode: string | null;
    city: string | null;
    /** ISO 3166-1 alpha-2, e.g. "DE". */
    country: string;
  };
  productionSite: string | null;
  scope: string;
  category: string | null;
  standards: { code: string; title: string }[];
  products: { name: string; brand: string | null; articleNo: string | null; description: string | null }[];
  /** YYYY-MM-DD */
  issueDate: string | null;
  validUntil: string | null;
  auditDate: string | null;
  signatory: { name: string; title: string } | null;
  /** data: URIs of private images (never public URLs). */
  images: { signature: string | null; stamp: string | null; companyLogo: string | null };
  /** null for drafts: token and QR code are created on issue. */
  verification: {
    url: string;
    displayUrl: string;
    /** SVG markup generated by the qrcode library (trusted). */
    qrSvg: string;
    /** Printed size incl. quiet zone, chosen so the code itself is ≥ 25 mm. */
    qrSizeMm: number;
  } | null;
};

export type RenderOptions = {
  /** Base URL for fonts and the logo ("" = same origin; Playwright maps its own). */
  assetBase: string;
  /** print = exact A4 pages; preview = pages on a grey desk, zoomed to fit. */
  mode: "print" | "preview";
};
